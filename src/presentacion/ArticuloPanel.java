    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        // TODO add your handling code here:
         try {
        Articulo articulo = obtenerArticuloFormulario();

        if (idArticuloEditar == 0) {
            articuloNegocio.agregar(articulo);
            JOptionPane.showMessageDialog(this, "Artículo registrado correctamente.");
        } else {
            articuloNegocio.editar(articulo);
            JOptionPane.showMessageDialog(this, "Artículo editado correctamente.");
        }

        limpiar();

        if (listaArticuloPanel != null) {
            listaArticuloPanel.cargarTabla(articuloNegocio.listar());
        }

        if (estadisticaPanel != null) {
            estadisticaPanel.actualizarEstadisticas();
        }

    } catch (DatoInvalidoException | ArticuloDuplicadoException e) {

        JOptionPane.showMessageDialog(
                this,
                e.getMessage(),
                "Error",
                JOptionPane.ERROR_MESSAGE
        );

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(
                this,
                "La cantidad y el precio deben ser numéricos.",
                "Error",
                JOptionPane.ERROR_MESSAGE
        );
    }
        
        
         
        
        
    }//GEN-LAST:event_btnAgregarActionPerformed


