    private Articulo obtenerArticuloFormulario() {

        String codigo = txtCodigo.getText().trim();
        String nombre = txtNombre.getText().trim();
        String categoria = cmbCategoria.getSelectedItem().toString();
        int cantidad = Integer.parseInt(txtCantidad.getText().trim());
        double precio = Double.parseDouble(txtPrecio.getText().trim());
        boolean disponible = chkDisponible.isSelected();
        String descripcion = txtDescripcion.getText().trim();

        Articulo articulo = new Articulo(
                idArticuloEditar,
                codigo,
                nombre,
                categoria,
                cantidad,
                precio,
                disponible,
                descripcion
        );

        return articulo;
    }

    public void limpiar() {
        idArticuloEditar = 0;
        txtCodigo.setText("");
        txtNombre.setText("");
        cmbCategoria.setSelectedIndex(0);
        txtCantidad.setText("");
        txtPrecio.setText("");
        chkDisponible.setSelected(false);
        txtDescripcion.setText("");
    }

    public void cargarProductoParaEditar(Articulo articulo) {
        idArticuloEditar = articulo.getId();

        txtCodigo.setText(articulo.getCodigo());
        txtNombre.setText(articulo.getTitulo());
        cmbCategoria.setSelectedItem(articulo.getCategoria());
        txtCantidad.setText(String.valueOf(articulo.getCantidad()));
        txtPrecio.setText(String.valueOf(articulo.getPrecio()));
        chkDisponible.setSelected(articulo.isDisponible());
        txtDescripcion.setText(articulo.getDescripcion());

    }

